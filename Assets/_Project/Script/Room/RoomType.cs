// Виды комнат. Новые значения добавляем ТОЛЬКО в конец списка:
// Unity хранит выбор в префабах как номер, и вставка в середину перепутает уже выставленные типы.
public enum RoomType
{
    Hub,
    Combat,
    Shop,
    Upgrade,
    Item,
    Boss,
    Vault,   // хранилище (пока не используется в картах уровней)
    Elite,   // элитные враги: два сундука, один из них открывается ключом
    Start,   // стартовая безопасная комната уровня
    Exit     // комната выхода: награда уровня и дверь на следующий уровень
}
